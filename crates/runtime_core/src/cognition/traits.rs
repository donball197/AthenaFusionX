//! Shared traits and core cognitive types.

use async_trait::async_trait;
use serde::{Deserialize, Serialize};
use std::collections::HashMap;
use uuid::Uuid;

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DecisionReason {
    pub confidence: f32,
    pub supporting_evidence: Vec<String>,
    pub policy_trigger: Option<String>,
    pub expected_cost: f32,
    pub rationale: String,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub enum ExecutiveDecisionKind {
    Continue,
    Pause,
    Abort,
    Replan,
    Escalate,
    Delegate { target: String, instruction: String },
    Reflect,
    Learn,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ExecutiveDecision {
    pub kind: ExecutiveDecisionKind,
    pub reason: DecisionReason,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub enum MissionStatus {
    Active,
    Paused,
    Completed,
    Failed,
    Aborted,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct MissionState {
    pub id: Uuid,
    pub directive: String,
    pub priority: f32,
    pub health: f32,
    pub status: MissionStatus,
    pub intent: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Goal {
    pub id: Uuid,
    pub title: String,
    pub description: String,
    pub priority: f32,
    pub objectives: Vec<Objective>,
    pub status: GoalStatus,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Objective {
    pub id: Uuid,
    pub title: String,
    pub tasks: Vec<TaskRef>,
    pub status: ObjectiveStatus,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TaskRef {
    pub id: Uuid,
    pub title: String,
    pub status: TaskStatus,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub enum GoalStatus {
    Pending,
    Active,
    Completed,
    Suspended,
    Abandoned,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub enum ObjectiveStatus {
    Pending,
    Active,
    Completed,
    Failed,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub enum TaskStatus {
    Pending,
    Running,
    Succeeded,
    Failed,
    Skipped,
}

/// Raw mission evidence produced by execution.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct MissionOutcome {
    pub mission_id: Uuid,
    pub success: bool,
    pub evidence_summary: String,
    pub failures: Vec<String>,
    pub successful_strategies: Vec<String>,
    pub raw_telemetry: String,
    pub failed_strategy_id: Option<Uuid>,
}

/// Belief adjustment generated by reflection.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct BeliefUpdate {
    pub target: Uuid,
    pub delta: f32,
}

/// Memory consolidation event.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct MemoryUpdate {
    pub category: String,
    pub content: String,
}

/// Output of the reflection process.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ReflectionReport {
    pub mission_id: Uuid,
    pub lessons: Vec<String>,
    pub confidence: f32,
    pub recommended_strategy: Option<String>,
    pub memory_updates: Vec<MemoryUpdate>,
    pub belief_updates: Vec<BeliefUpdate>,
    pub metrics: HashMap<String, f32>,
}

/// Context provided to strategy selection.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct StrategyContext {
    pub goal: Goal,
    pub history: Vec<MissionOutcome>,
    pub active_beliefs: HashMap<Uuid, f32>,
    pub available_resources: f32,
    pub mission_type: String,
}

/// Prediction generated before execution.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Prediction {
    pub action_id: Uuid,
    pub expected_state: String,
    pub confidence: f32,
    pub cost_estimate: f32,
    pub timestamp: u64,
}

/// Prediction error result.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PredictionEvaluation {
    pub accuracy: f32,
    pub error: f32,
}

/// Executive decision interface.
#[async_trait]
pub trait Executive: Send + Sync {
    async fn decide(&self, state: &MissionState) -> ExecutiveDecision;
}

/// Goal lifecycle interface.
#[async_trait]
pub trait GoalLifecycle: Send + Sync {
    async fn create_goal(&self, title: &str, description: &str, priority: f32) -> Goal;

    async fn list_active(&self) -> Vec<Goal>;
}

/// Reflection learning interface.
#[async_trait]
pub trait Reflector: Send + Sync {
    async fn reflect(&self, outcome: &MissionOutcome) -> anyhow::Result<ReflectionReport>;
}

/// Strategy adaptation interface.
#[async_trait]
pub trait Strategist: Send + Sync {
    async fn select_strategy(&self, context: &StrategyContext) -> anyhow::Result<String>;
}
