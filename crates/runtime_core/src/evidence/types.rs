use crate::evidence::BeliefVector;
use serde::{Deserialize, Serialize};
use std::time::{SystemTime, UNIX_EPOCH};
use uuid::Uuid;

/// Explicit failure taxonomy to prevent infinite retry loops on security denials.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub enum ExecutionFailureKind {
    /// Hard security / policy violation (e.g. PATH_TRAVERSAL_DENIED).
    /// MUST immediately zero out strategy belief and mark path as ineligible.
    PolicyDenial { path: String, reason: String },

    /// Target file/resource missing on disk (e.g., ENOENT os error 2).
    ResourceNotFound { target: String },

    /// Non-zero exit code or tool runtime failure.
    ExecutionError { exit_code: i32, stderr: String },

    /// Lock timeout or transient resource contention.
    TransientTimeout { resource: String },
}

/// Explicit provenance tracking for evidence claims.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub enum ProvenanceLevel {
    /// Directly verified via tool execution or file contents read from disk.
    Observed { byte_count: usize },

    /// Derived logically from AST symbols or dependency graphs.
    Inferred { basis_symbol: String, confidence: f32 },

    /// Unverified assumption or heuristic generated by model reasoning.
    Hypothesized { rationale: String },
}

impl Default for ProvenanceLevel {
    fn default() -> Self {
        Self::Hypothesized { rationale: "Unverified initial assumption".to_string() }
    }
}

/// Raw observation string coming out of the RoboticExecutor.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Observation {
    pub raw: String,
    pub source: String, // "executor", "grep", "read_file", "podman", etc.
    pub success: bool,
    pub latency_ms: u64,
    pub failure_kind: Option<ExecutionFailureKind>,
}

/// Semantic classification of an observation.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum EvidenceKind {
    CommandSuccess,
    CommandFailure,
    FileRead,
    FileWrite,
    PatternMatch,
    SecurityViolation,
    ArchitecturalSmell,
    PositiveSignal,
    Neutral,
}

/// Fully materialised evidence node that can be inserted into the EvidenceGraph.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Evidence {
    pub id: Uuid,
    pub observation: Observation,
    pub kind: EvidenceKind,
    pub provenance: ProvenanceLevel,
    pub belief_delta: BeliefVector,
    pub timestamp: u64,
    pub related_strategy_id: Option<Uuid>,
}

impl Evidence {
    pub fn from_observation(
        obs: Observation,
        kind: EvidenceKind,
        belief_delta: BeliefVector,
        related_strategy_id: Option<Uuid>,
    ) -> Self {
        let timestamp = SystemTime::now().duration_since(UNIX_EPOCH).unwrap_or_default().as_secs();

        let provenance = if crate::evidence_markers::has_mutation_marker(&obs.raw)
            || crate::evidence_markers::has_patch_satisfied_marker(&obs.raw)
            || crate::evidence_markers::has_recon_marker(&obs.raw)
            || obs.raw.contains("[WRITE_NOOP]")
            || obs.raw.contains("[READ_FUNCTION_OK]")
            || obs.raw.contains("[SEARCH_CHECKED_OK]")
            || obs.raw.contains("[SEARCH_MEMORY_OK]")
        {
            ProvenanceLevel::Observed { byte_count: obs.raw.len() }
        } else {
            ProvenanceLevel::Hypothesized { rationale: "Derived from executor stdout".to_string() }
        };

        Self {
            id: Uuid::new_v4(),
            observation: obs,
            kind,
            provenance,
            belief_delta,
            timestamp,
            related_strategy_id,
        }
    }

    /// Heuristic classifier with explicit PolicyDenial extraction.
    pub fn classify(raw: &str, success: bool) -> (EvidenceKind, Option<ExecutionFailureKind>) {
        let lower = raw.to_lowercase();

        if lower.contains("sandbox_violation")
            || lower.contains("path_traversal")
            || lower.contains("threat pattern")
        {
            let path = raw.split(':').nth(1).unwrap_or("unknown_path").trim().to_string();
            return (
                EvidenceKind::SecurityViolation,
                Some(ExecutionFailureKind::PolicyDenial {
                    path,
                    reason: "PATH_TRAVERSAL_DENIED".to_string(),
                }),
            );
        }

        if lower.contains("no such file or directory") || lower.contains("os error 2") {
            return (
                EvidenceKind::CommandFailure,
                Some(ExecutionFailureKind::ResourceNotFound { target: raw.to_string() }),
            );
        }

        if lower.contains("pattern_not_found")
            || lower.contains("function_not_found")
            || lower.contains("action_failed")
            || lower.contains("[action failed]")
        {
            return (
                EvidenceKind::CommandFailure,
                Some(ExecutionFailureKind::ExecutionError {
                    exit_code: 1,
                    stderr: raw.to_string(),
                }),
            );
        }

        if lower.contains("[write_ok]")
            || lower.contains("[write_noop]")
            || lower.contains("[patch_function_ok]")
            || lower.contains("[patch_idempotent_ok]")
            || lower.contains("[diff_patch_ok]")
            || lower.contains("[replace_lines_ok]")
        {
            return if success {
                (EvidenceKind::FileWrite, None)
            } else {
                (EvidenceKind::CommandFailure, None)
            };
        }

        if lower.contains("[read_ok]")
            || lower.contains("[read_chunk_ok]")
            || lower.contains("[read_function_ok]")
        {
            return if success {
                (EvidenceKind::FileRead, None)
            } else {
                (EvidenceKind::CommandFailure, None)
            };
        }

        if lower.contains("[search_code_ok]")
            || lower.contains("[search_checked_ok]")
            || lower.contains("[search_memory_ok]")
        {
            return if success {
                (EvidenceKind::PatternMatch, None)
            } else {
                (EvidenceKind::CommandFailure, None)
            };
        }

        if lower.contains("[cmd_ok]") {
            return if success {
                (EvidenceKind::CommandSuccess, None)
            } else {
                (EvidenceKind::CommandFailure, None)
            };
        }

        if lower.contains("todo") || lower.contains("placeholder") {
            return (EvidenceKind::ArchitecturalSmell, None);
        }

        if success {
            (EvidenceKind::PositiveSignal, None)
        } else {
            (EvidenceKind::Neutral, None)
        }
    }
}

#[cfg(test)]
mod provenance_tests {
    use super::*;

    #[test]
    fn recognizes_all_executor_markers_as_observed() {
        for marker in [
            "[READ_CHUNK_OK] File: a.rs | Lines 1-5 of 5",
            "[WRITE_OK] out.md",
            "[WRITE_NOOP] out.md -- content identical to existing file",
            "[PATCH_FUNCTION_OK] a.rs:f",
            "[PATCH_IDEMPOTENT_OK] a.rs:f",
            "[DIFF_PATCH_OK] a.rs",
            "[REPLACE_LINES_OK] a.rs",
            "[SEARCH_CODE_OK] Path: src | Query: 'x'",
            "[SEARCH_MEMORY_OK] query",
        ] {
            let (kind, _) = Evidence::classify(marker, true);
            let ev = Evidence::from_observation(
                Observation {
                    raw: marker.to_string(),
                    source: "test".into(),
                    success: true,
                    latency_ms: 0,
                    failure_kind: None,
                },
                kind,
                BeliefVector::ZERO,
                None,
            );
            assert!(
                matches!(ev.provenance, ProvenanceLevel::Observed { .. }),
                "expected Observed for {}",
                marker
            );
        }
    }
}
